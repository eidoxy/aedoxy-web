import * as React from "react"

import { cn } from "@/lib/utils"

// Adapted from the shadcn dashboard template; surface, line and shadow come from the Aedoxy tokens.
function Card({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="card"
      className={cn(
        "flex min-w-0 flex-col gap-5 rounded-[18px] border border-line bg-surface py-5 text-sm text-card-foreground shadow-card",
        className
      )}
      {...props}
    />
  )
}

